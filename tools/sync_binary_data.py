"""
Copy the group database generated by MultiPieGen into multipie/binary_data.

    python tools/sync_binary_data.py <MultiPieGen checkout> [--allow-dirty]

The files in <MultiPieGen>/multipiegen/binary_data (info.pkl and {PG,SG,MPG,MSG}/*.pkl) replace those in
multipie/binary_data, and multipie/binary_data/SOURCE.txt records the repository and the commit they come from.
The checkout must be clean in multipiegen/binary_data, so that the commit identifies the data (unless --allow-dirty).
"""

import argparse
import datetime
import os
import shutil
import subprocess
import sys

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DST = os.path.join(TOP, "multipie", "binary_data")
GROUP_TYPES = ["PG", "SG", "MPG", "MSG"]


# ==================================================
def git(src, *args):
    """
    Output of a git command in src.
    """
    return subprocess.run(["git", "-C", src, *args], capture_output=True, text=True, check=True).stdout.strip()


# ==================================================
def check_source(src_dir):
    """
    Check the layout of the binary data to copy, and return the number of the group files.
    """
    if not os.path.isfile(os.path.join(src_dir, "info.pkl")):
        raise SystemExit(f"no info.pkl in {src_dir}.")
    n = 0
    for tp in GROUP_TYPES:
        d = os.path.join(src_dir, tp)
        if not os.path.isdir(d):
            raise SystemExit(f"no {tp} directory in {src_dir}.")
        files = [f for f in os.listdir(d) if f.endswith(".pkl")]
        if not files:
            raise SystemExit(f"no binary file in {d}.")
        n += len(files)
    return n


# ==================================================
def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("src", help="MultiPieGen checkout.")
    parser.add_argument("--allow-dirty", action="store_true", help="copy also uncommitted binary data.")
    args = parser.parse_args()

    src = os.path.abspath(args.src)
    src_dir = os.path.join(src, "multipiegen", "binary_data")
    n = check_source(src_dir)

    commit = git(src, "rev-parse", "HEAD")
    dirty = git(src, "status", "--porcelain", "--", "multipiegen/binary_data")
    if dirty and not args.allow_dirty:
        raise SystemExit(f"uncommitted changes in multipiegen/binary_data of {src}:\n{dirty}")
    try:
        repository = git(src, "remote", "get-url", "origin")
    except subprocess.CalledProcessError:
        repository = "(no remote)"

    # replace the binary data.
    for tp in GROUP_TYPES:
        shutil.rmtree(os.path.join(DST, tp), ignore_errors=True)
        shutil.copytree(os.path.join(src_dir, tp), os.path.join(DST, tp), ignore=shutil.ignore_patterns("*.tmp", ".*"))
    shutil.copy2(os.path.join(src_dir, "info.pkl"), os.path.join(DST, "info.pkl"))

    with open(os.path.join(DST, "SOURCE.txt"), "w", encoding="utf-8") as f:
        f.write("Group database generated by MultiPieGen (copied by tools/sync_binary_data.py).\n")
        f.write(f"repository: {repository}\n")
        f.write(f"commit: {commit}{' (with uncommitted changes)' if dirty else ''}\n")
        f.write(f"copied: {datetime.date.today().isoformat()}\n")
        f.write(f"files: info.pkl and {n} group files\n")

    print(f"copied info.pkl and {n} group files from {src_dir} ({commit[:8]}{', dirty' if dirty else ''}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
